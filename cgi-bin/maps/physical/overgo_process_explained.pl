#!/usr/bin/perl
use utf8;

######################################################################
#
#  This program is barely a program at all, although it does pull
#  somewhat from the database and so ended up a program.
#
#  Nevertheless, the point here is really to generate a largely 
#  static page, one which serves to explicate the Overgo Plating
#  process.
# 
######################################################################

use strict;
use CXGN::Page;
use CXGN::DB::Connection;
use CXGN::DB::Physical;
use CXGN::Page::FormattingHelpers qw/blue_section_html page_title_html/;

# Presets.
my $overgo_stats_page = 'overgo_stats.pl';
my $physical_map_page = '/cview/map.pl?map_id=9&amp;physical=1';
my $physical_map_overview = '/cview/map.pl?map_id=9&amp;physical=1';
my $soop_home = 'http://genome.nhgri.nih.gov/soop/';
my $agi_page = 'http://www.genome.arizona.edu/fpc/tomato/';
my $bac_search_page = '/search/direct_search.pl?search=BACs';

# Connect to the db.
my $dbh=CXGN::DB::Connection->new('physical');

# Prepare the page.
our $page = CXGN::Page->new( "Sobre o processo de placas de overgo", "Robert Buels");

# Find out how many plates have been processed to date.
my $plates_sth = $dbh->prepare("SELECT COUNT(DISTINCT plate_number) FROM overgo_plates");
$plates_sth->execute;
my $number_of_plates_processed = $plates_sth->fetchrow_array;
$plates_sth->finish;
$number_of_plates_processed || $page->error_page("Nenhuma placa de overgo encontrada no banco de dados físico.");

# Print the page.
$page->header("Processo de placas de overgo");
print page_title_html('Sobre o processo de placas de overgo');

print blue_section_html('Processo de placas de overgo',<<EOH);
This page explains (briefly) the nature of the Overgo Plating experiments
conducted at SGN.  We also explain the terminology used on our
<a href="$overgo_stats_page">Página de estatísticas de overgo</a> in relation to the
various stages of processing we have conducted.
EOH

print blue_section_html('Sobre o processo de placas de overgo',<<EOH);
<p>As placas de overgo têm 96 poços, organizados em 8 linhas e 12 colunas. A sequência de DNA de uma sonda de overgo, um marcador sequenciado da coleção de mapas, é atribuída a cada poço. Os poços são então <i>pooled</i> usando o <a href="$soop_home">Soop</a>
para produzir 20 conjuntos (8 conjuntos de linhas + 12 conjuntos de colunas).
</p>

<p>As placas de BACs são testadas contra esses 20 conjuntos de cada placa para identificar quais BACs correspondem a cada conjunto. Isso permite inferir as correspondências entre BACs e sondas. Diz-se que uma sonda que corresponde a um ou mais BACs os ancora ao <a href="$physical_map_page">Mapa genético</a> and
is thus referred to as an "anchor point".
</p>


<p>Para ancorar com sucesso a uma sonda, o BAC deve:</p>

<ol>
<li>corresponder ao conjunto da linha e ao da coluna e</li>
<li>não corresponder a nenhum outro conjunto dessa placa.</li>
</ol>

<p>Quando os BACs correspondem a mais de uma linha e coluna da placa, eles são classificados como <i>ambiguous</i> BACs. Eles são armazenados separadamente e não são exibidos em <a href="$physical_map_overview">physical
map</a>.
</p>
<a name="fpc_contigging"></a>
EOH

print blue_section_html('Processo FPC',<<EOH);
Meanwhile, working from the other end, our collaborators at the
<a href="$agi_page">Arizona Genomics Institute</a> estão usando <i>Fingerprint
Contigging (FPC)</i> techniques to assemble the BAC collection into contigs.
The BAC &lt;--&gt; map position matches generated by our overgo plating experiment
are used to inform the FPC process and improve the contigging conducted there.
EOH

print blue_section_html('In silico processing of BAC anchoring',<<EOH);
<p>After establishing the unambiguous BAC &lt;--&gt; probe associations, a further stage
of in silico processing was done to check for the <i>plausibility</i> das correspondências de BACs. O conjunto plausível inicial contém todos os BACs ancorados sem ambiguidade. Depois, removemos os BACs que não atendem a determinados critérios.
</p>

<p>Em geral, espera-se que um BAC corresponda apenas a uma parte de um cromossomo. Por isso, primeiro removemos do conjunto plausível os BACs ancorados a marcadores de dois ou mais cromossomos. [<i>N.B.</i> - Quando houver dados de todas as placas, pretendemos realizar análises mais complexas. Se um BAC tiver vários pontos de ancoragem próximos em um cromossomo e apenas um ponto isolado em outro local, poderá ser possível identificar este último como anômalo. Porém, ainda não há dados suficientes para essa análise.]
</p>

<p>Também se espera que os BACs se ancorem principalmente a uma parte do cromossomo, em vez de se distribuírem aleatoriamente ao longo dele. Assim, um BAC plausível deve ter uma sequência de pontos de ancoragem próximos entre si. Foi escolhida a distância máxima de 5.0 cM entre pontos adjacentes de um BAC. BACs que violam esse critério são removidos do conjunto plausível.
</p>

<p>Por fim, consideramos plausíveis os contigs de BACs gerados por FPC se:</p>

<ol>
<li>Todos os BACs ancorados que os compõem estiverem no mesmo cromossomo e</li>
<li>Há uma sequência de BACs ao longo do contig em que dois pontos de ancoragem consecutivos nunca estão separados por mais de 5.0 cM.</li>
</ol>
EOH

print blue_section_html('Resumo dos termos',<<EOH);
<p>Esta seção resume os termos usados na página de
<a href="$overgo_stats_page">Estatísticas das placas de overgo</a> . Consulte essa página para ver os números de cada item.</p>

<p>Os termos estão listados em ordem alfabética.</p>
</div>

<div class="indentedcontent">
<dl id="overgodefs">
<dt><a name="anchorpoint"></a>
Anchor Point
</dt>
<dd>
An overgo probe (qv) which has successfully been associated with one
or more BACs is said to anchor them to the map and is thus referred to as
an "anchor point".
</dd>

<dt><a name="bacs"></a>
BACs
</dt>
<dd>
BACs são <i>Cromossomos artificiais bacterianos</i>. A mesma biblioteca de BACs é usada na montagem de contigs por FPC e no processo de placas de overgo. Há 129024 clones BAC nas placas da biblioteca, mas nem todos são válidos; por isso, o número relatado de BACs é menor.
</dd>

<dt><a name="emptywells"></a>
Empty wells
</dt>
<dd>
As placas de overgo geralmente têm 96 poços. Para facilitar a associação inequívoca entre uma sonda e seu poço, a distribuição dos marcadores nas placas foi <i>deconvoluted</i> para que dois marcadores no mesmo conjunto não fiquem a menos de 5.0 cM entre si no <a
href="$physical_map_page">Mapa genético</a>. Por isso, às vezes é necessário deixar poços vazios para garantir uma boa dispersão. Nem toda placa de overgo contém 96 sondas: a soma de sondas e poços vazios deve ser 96.
</dd>

<dt><a name="hittheplates"></a>
Correspondência com as placas
</dt>
<dd>
Considera-se que BACs que correspondem a pelo menos um conjunto de linha ou coluna de uma placa de overgo corresponderam às placas, pois há alguma correspondência com as sequências de marcadores genéticos conhecidas pelo SGN.
</dd>

<dt><a name="plates"></a>
Overgo Plates
</dt>
<dd>
Each overgo plate contains up to 96 probes, arranged in 8 rows and 12 columns.
To date, $number_of_plates_processed plates have been processed.
</dd>

<dt><a name="probes"></a>
Overgo Probes
</dt>
<dd>
Cada <i>probe</i> corresponde a um marcador sequenciado da coleção de mapas de tomate do SGN. Cada marcador é colocado uma vez nas placas de overgo e conta como uma sonda. Se associar BACs ao mapa com sucesso, a sonda é um ponto de ancoragem.
</dd>

<dt><a name="plausible"></a>
Posições plausíveis de BACs
</dt>
<dd>
O processo de placas de overgo pode gerar associações de um BAC a várias sondas. Se elas estiverem no mesmo cromossomo e relativamente próximas, o BAC está <i>plausibly</i> ancorado a esse cromossomo por esses pontos. O critério de proximidade exige que dois pontos consecutivos estejam separados por no máximo 5.0 cM. Um contig FPC cujos BACs plausivelmente ancorados estejam no mesmo cromossomo é um <i>plausible contig</i>.
</dd>

<dt><a name="ambiguity"></a>
Unambiguous matching, a.k.a. plausible matching
</dt>
<dd>
<p>A ambiguidade diz respeito à correspondência entre um BAC e uma placa de overgo. Se o BAC corresponder exatamente a um conjunto de linha e um de coluna, a correspondência a uma sonda é clara e a ancoragem não é ambígua. Caso contrário, o conjunto de sondas possíveis constitui as correspondências ambíguas desse BAC.</p>
</dd>

</dl>
EOH

print blue_section_html('Links',<<EOH);
<ul>
